"""Converted SUMO networks record portable paths, never the converting machine's.

netconvert echoes its input and output paths into a comment at the top of
every network it writes, and ``scripts/convert_opendrive_maps.py`` lists them
again in ``conversion_report.json``. Both ship in ``opencda_marl/assets/maps``,
so the converter rewrites them repo-relative or ``$CARLA_ROOT``-relative, and
touches nothing past the comment.
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
MAPS = REPO / "opencda_marl" / "assets" / "maps"
_HEADER_PATH = re.compile(
    r'<(?:opendrive-files|output-file|sumo-net-file|opendrive-output) value="([^"]*)"')
# A drive letter, a UNC or POSIX root, or a home directory.
_ABSOLUTE = re.compile(r'^(?:[A-Za-z]:[\\/]|[\\/]|~)')


def _converter():
    spec = importlib.util.spec_from_file_location(
        "convert_opendrive_maps", REPO / "scripts" / "convert_opendrive_maps.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_paths_are_recorded_relative_to_the_repo_or_carla(tmp_path):
    conv = _converter()
    repo, carla = tmp_path / "checkout", tmp_path / "carla"
    assert conv.portable_path(repo / "opencda_marl" / "assets" / "x.xodr",
                              repo=repo, carla_root=carla) == "opencda_marl/assets/x.xodr"
    assert conv.portable_path(carla / "CarlaUE4" / "Town01.xodr",
                              repo=repo, carla_root=carla) == "$CARLA_ROOT/CarlaUE4/Town01.xodr"
    # Outside both: the name alone (the report sits next to the networks).
    assert conv.portable_path(tmp_path / "elsewhere" / "Town01.net.xml",
                              repo=repo, carla_root=None) == "Town01.net.xml"


def test_the_header_is_rewritten_and_the_network_is_not(tmp_path):
    conv = _converter()
    repo, carla = tmp_path / "checkout", tmp_path / "carla"
    source = carla / "Maps" / "Town01.xodr"
    target = repo / "artifacts" / "maps" / "Town01.net.xml"
    target.parent.mkdir(parents=True)
    body = (b'-->\r\n\r\n<net version="1.20">\r\n'
            b'    <param key="note" value="' + str(source).encode() + b'"/>\r\n</net>\r\n')
    header = ('<?xml version="1.0" encoding="UTF-8"?>\r\n\r\n<!-- generated by netconvert\r\n'
              f'    <input>\r\n        <opendrive-files value="{source}"/>\r\n    </input>\r\n'
              f'    <output>\r\n        <output-file value="{target}"/>\r\n    </output>\r\n')
    target.write_bytes(header.encode() + body)

    assert conv.scrub_net_header(target, repo=repo, carla_root=carla) is True
    data = target.read_bytes()
    assert data.endswith(body), "everything from the end of the comment on is byte-identical"
    head = data[:data.find(b"-->")].decode()
    assert '<opendrive-files value="$CARLA_ROOT/Maps/Town01.xodr"/>' in head
    assert '<output-file value="artifacts/maps/Town01.net.xml"/>' in head
    assert "\r\n" in head, "line endings are kept"
    assert conv.scrub_net_header(target, repo=repo, carla_root=carla) is False, "idempotent"


@pytest.mark.parametrize("net", sorted(MAPS.glob("*.net.xml")), ids=lambda p: p.name)
def test_shipped_networks_carry_no_absolute_paths(net):
    with net.open("rb") as handle:
        head = handle.read(8192)
    head = head[:head.find(b"-->")].decode("utf-8")
    values = _HEADER_PATH.findall(head)
    assert values, "the netconvert configuration comment is present"
    assert not [v for v in values if _ABSOLUTE.match(v)], values


def test_the_conversion_report_carries_no_absolute_paths():
    rows = json.loads((MAPS / "conversion_report.json").read_text(encoding="utf-8"))
    recorded = [row[key] for row in rows for key in ("source", "net", "opendrive_out")
                if row.get(key)]
    assert recorded
    assert not [v for v in recorded if _ABSOLUTE.match(v)], recorded
